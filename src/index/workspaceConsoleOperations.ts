function formatFlag(flag: string, value: string): string {
	return `-${flag}="${value.replace(/"/g, '\\"')}"`;
}

/**
 * Builds the exact `dotnet <dll> -operation=... -flag="value" ...` command
 * line for one operation. Booleans are always emitted as `-flag=true`/`=false`
 * (never a bare flag) — `GetParameterValue(name, bool defValue)` treats a
 * present-but-empty value as "absent" (see file doc), so a bare `-autoExit`
 * with no `=value` would silently behave as `false`.
 */
export function buildWorkspaceConsoleCommand(
	dllPath: string,
	op: WCOperation,
	baseValues: Record<string, string | boolean>,
	opValues: Record<string, string | boolean>,
	extraArgs: string
): string {
	const parts: string[] = [`dotnet "${dllPath}"`, `-operation=${op.op}`];
	const emit = (param: WCParam, raw: string | boolean | undefined) => {
		if (raw === undefined || raw === "") {
			return;
		}
		if (param.kind === "bool") {
			parts.push(`-${param.flag}=${raw ? "true" : "false"}`);
			return;
		}
		parts.push(formatFlag(param.flag, String(raw)));
	};
	for (const param of WORKSPACE_CONSOLE_BASE_PARAMS) {
		emit(param, baseValues[param.flag]);
	}
	for (const param of op.params) {
		emit(param, opValues[param.flag]);
	}
	const trimmedExtra = extraArgs.trim();
	if (trimmedExtra) {
		parts.push(trimmedExtra);
	}
	return parts.join(" ");
}
