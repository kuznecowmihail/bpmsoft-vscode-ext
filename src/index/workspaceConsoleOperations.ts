/**
 * Catalog of `WorkspaceConsole` operations and their command-line parameters —
 * reverse-engineered directly from `BPMSoft.Tools.WorkspaceConsole.dll` /
 * `BPMSoft.Tools.Common.dll` (decompiled with ilspycmd against a real 1.9.1
 * install, 2026-09-09), not from Creatio documentation — BPMSoft's own build
 * has both renamed and added/removed operations relative to stock Creatio, so
 * the Creatio Academy parameter tables don't reliably apply here.
 *
 * Ground truth used to build this table:
 * - `WorkspaceConsoleOperation` enum (`BPMSoft.Tools.WorkspaceConsole.dll`,
 *   XML doc) — the full set of operation names.
 * - `WorkspaceConsoleApplication.ExecuteOperation`'s `switch` — only ~62 of
 *   the 69 enum values actually have a `case`; the rest (`UpdatePackages`,
 *   `SaveVersionSvnContent`, `InstallBundlePackages`, `ConcatSvnRepositories`,
 *   `InstallTestPackages`, `InstallUnitTestPackages`,
 *   `InstallTestPackagesBySuffix`) fall through to `default` and throw
 *   `UnsupportedTypeException` — dead in this build, deliberately omitted
 *   below rather than offered as buttons that can't work.
 * - Each operation's own method body — every `CheckRequiredCommandLineParameter(name, ...)`
 *   call is a hard requirement; the exact CLI flag string is each field's own
 *   `...OptionName` constant value (read via reflection), not guessed from
 *   the C# property name — several differ in casing/spelling from their
 *   property (`CultureName` reads flag `culturename`, all-lowercase;
 *   `PublishAngularComponentOnlySystemPackages` reads flag
 *   `onlySystemPackages`).
 * - `WorkspaceConsoleCommandLine.CommandsWithRequiredConfRuntimeParentDirectoryParameter`
 *   — the exact list of operations where `confRuntimeParentDirectory` is
 *   enforced by `Validate()` before the operation even runs.
 * - `BaseApplicationCommandLine<TOperations>`'s own registered parameters —
 *   `-operation`, `-user`, `-workspaceName` are `IsRequired = true` for
 *   *every* operation; `-password`/`-autoExit`/`-logPath` are optional. Note
 *   the flag is `-user`/`-password`, not `-userName`/`-userPassword` despite
 *   the C# properties being named that way.
 *
 * Not modeled here (by design, not oversight): every operation's long tail of
 * filter/tuning options (`includedSchemas`, `excludedSchemaColumns`,
 * `schemaManagerNames`, `validate*`, ...) — modeling exhaustively would bloat
 * the form for little real benefit. Only parameters that are hard-required or
 * commonly needed are exposed as typed fields; the panel also offers a free
 * "additional arguments" text box appended verbatim to the generated command
 * line for anything else (see `WorkspaceConsoleOperationsPanel`).
 */

export type WCParamKind = "text" | "path" | "bool" | "int" | "password";

export interface WCParam {
	/** Exact CLI option name, e.g. the command line reads it as `-flag=value`. */
	flag: string;
	label: string;
	kind: WCParamKind;
	required?: boolean;
	hint?: string;
	/** Pre-fill from the app root path when the field is first shown. */
	defaultFromAppRoot?: boolean;
}

export interface WCOperation {
	/** Exact `WorkspaceConsoleOperation` enum member name. */
	op: string;
	category: string;
	caption: string;
	description: string;
	params: WCParam[];
	/** Mutates/deletes existing data (DB rows, files, packages) — shown with an extra confirmation. */
	destructive?: boolean;
}

